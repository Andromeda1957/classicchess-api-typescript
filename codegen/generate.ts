// Generate the SDK types from its OpenAPI contract with openapi-typescript.
// Run through the SDK npm scripts after the root workspace install. The exported
// SDK carries this tool in codegen/ with its own independent install. TypeScript 6
// retains the compiler API required here; SDK builds use TypeScript 7.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const packageRoot = pathToFileURL(resolve(process.cwd()) + sep);
// A standalone export carries the contract; the monorepo serves it from the site.
const specCandidates = [
  new URL('contracts/openapi.yaml', packageRoot),
  new URL('../../core/templates/core/pages/openapi.yaml', packageRoot),
];
const spec = specCandidates.find(candidate => existsSync(candidate));
if (!spec) {
  throw new Error('OpenAPI contract not found in contracts/ or the website templates.');
}
const target = new URL('src/schema.ts', packageRoot);
const header = '// Generated by codegen/generate.ts (openapi-typescript) from OpenAPI. Do not edit.\n';

const ast = await openapiTS(pathToFileURL(fileURLToPath(spec)), {
  // One exported alias per component schema, named exactly as in the contract.
  rootTypes: true,
  rootTypesNoSchemaPrefix: true,
});
const output = header + astToString(ast);

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) {
    process.stderr.write('SDK types differ from OpenAPI; run `npm run generate:types`.\n');
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
